import { createAggregate, createEntity, createMixin } from '@redemeine/aggregate';
import { createProjection, inherit, type ProjectionDefinition } from '../src';

type Row = { id: string; count: number };
const row = createEntity<Row, 'row'>('row')
  .events({
    changed(state, event: { payload: { amount: number } }) {
      state.count += event.payload.amount;
    }
  })
  .commands((emit) => ({
    add: (_state, payload: { amount: number }) => emit.changed(payload)
  }))
  .build();

function apply<S>(projection: ProjectionDefinition<S>, state: S, type: string, payload: Record<string, unknown>) {
  projection.fromStream.handlers[type]!(
    state,
    {
      type,
      payload,
      aggregateType: 'store',
      aggregateId: 's',
      sequence: 1,
      timestamp: ''
    },
    { subscribeTo() {}, unsubscribeFrom() {} }
  );
}

function expectCanonical<S>(projection: ProjectionDefinition<S>, aggregate: { types: { events: Record<string, string> } }) {
  expect(Object.keys(projection.fromStream.handlers).sort()).toEqual([...new Set(Object.values(aggregate.types.events))].sort());
}

const initial = () => ({
  total: 0,
  rows: [
    { id: 'a', count: 0 },
    { id: 'b', count: 0 }
  ],
  byKey: { a: { id: 'a', count: 0 } }
});
const direct = () =>
  createAggregate('store', initial())
    .events({
      changed(state, event: { payload: { total: number } }) {
        state.total += event.payload.total;
      }
    })
    .entityList('rows', row)
    .entityMap('byKey', row, {}, { semanticName: 'keyed' })
    .valueObject('details')
    .build();

test('mirrors all canonical root, list and map wires; emitted events apply once to selected state', () => {
  const source = direct();
  const projection = createProjection('mirror').mirror(source).build();
  expectCanonical(projection, source);
  const state = projection.initialState('s');
  const emitted = source.process(source.initialState, {
    type: source.types.commands.rowsAdd!,
    payload: { id: 'a', amount: 2 }
  });
  expect(emitted).toHaveLength(1);
  apply(projection, state, emitted[0]!.type, emitted[0]!.payload as Record<string, unknown>);
  apply(projection, state, source.types.events['byKey:changed']!, { key: 'a', amount: 3 });
  apply(projection, state, 'store.changed.event', { total: 7 });
  expect(state).toEqual({
    total: 7,
    rows: [
      { id: 'a', count: 2 },
      { id: 'b', count: 0 }
    ],
    byKey: { a: { id: 'a', count: 3 } }
  });
  expect(source.initialState).toEqual(initial());
  expect(projection.initialState('another')).toEqual(initial());
});

test('mounted list/map overrides replace defaults and extend observes exactly one aggregate application', () => {
  const source = direct();
  const after = jest.fn();
  const projection = createProjection('custom')
    .mirror(source, {
      'rows:changed': (state, event) => {
        state.total += event.payload.amount;
      },
      'byKey:changed': inherit.extend((state, event) => {
        after(state.byKey.a.count, event.payload.amount);
        state.total += state.byKey.a.count;
      })
    })
    .build();
  const state = projection.initialState('s');
  apply(projection, state, source.types.events['rows:changed']!, { id: 'a', amount: 2 });
  apply(projection, state, source.types.events['byKey:changed']!, { key: 'a', amount: 3 });
  expect(state.rows[0]!.count).toBe(0);
  expect(state.total).toBe(5);
  expect(after).toHaveBeenCalledTimes(1);
  expect(after).toHaveBeenCalledWith(3, 3);
});

test('explicit suppression survives autogenerated aliases', () => {
  const source = createAggregate('store', initial()).entityList('rows', row).build();
  const wire = source.types.events['rows:changed']!;
  const projection = createProjection('suppressed').mirror(source, { 'rows:changed': undefined }).build();
  expect(projection.fromStream.handlers[wire]).toBeUndefined();
});

test('coincident mounted wires are deduplicated and retain compiled last-registration routing', () => {
  const source = createAggregate('store', { left: [{ id: 'a', count: 0 }], right: [{ id: 'a', count: 0 }] })
    .entityList('left', row)
    .entityList('right', row)
    .build();
  expect(source.types.events['left:changed']).toBe(source.types.events['right:changed']);
  expect(() => createProjection('duplicate').mirror(source, { 'left:changed': inherit, 'right:changed': inherit })).toThrow(
    'Ambiguous projection event handler'
  );
  const projection = createProjection('coincident').mirror(source).build();
  expectCanonical(projection, source);
  const state = projection.initialState('s');
  apply(projection, state, source.types.events['left:changed']!, { id: 'a', amount: 2 });
  expect(state).toEqual({ left: [{ id: 'a', count: 0 }], right: [{ id: 'a', count: 2 }] });
});

test('nested and mixin events inherit using compiled aliases without reconstructing names', () => {
  const parent = createEntity<{ id: string; rows: Row[] }, 'parent'>('parent').entityList('rows', row).build();
  const initialState = { parents: [{ id: 'p', rows: [{ id: 'a', count: 0 }] }], total: 0 };
  const mixin = createMixin<typeof initialState>()
    .events({
      bumped(state) {
        state.total++;
      }
    })
    .build();
  const source = createAggregate('store', initialState).mixins(mixin).entityList('parents', parent).build();
  const projection = createProjection('nested').mirror(source).build();
  expectCanonical(projection, source);
  const state = projection.initialState('s');
  apply(projection, state, source.types.events['parents:rowsChanged']!, { parentsId: 'p', id: 'a', amount: 4 });
  apply(projection, state, source.types.events.bumped!, {});
  expect(state.total).toBe(1);
  expect(state.parents[0]!.rows[0]!.count).toBe(4);
});

test('structural sources without mapped events retain root defaults and explicit initial state', () => {
  const source = {
    aggregateType: 'legacy',
    initialState: { total: 0 },
    pure: { eventProjectors: { changed() {} } },
    applyToDraft(state: { total: number }) {
      state.total++;
    }
  };
  const projection = createProjection('legacy', () => ({ total: 10 }))
    .mirror(source)
    .build();
  const state = projection.initialState('s');
  apply(projection, state, 'changed', {});
  expect(state.total).toBe(11);
});
