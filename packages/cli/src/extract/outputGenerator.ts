import * as ts from 'typescript';
import { TypeToZodConverter } from './typeConverter';
import { commentText, formatSchemaSource, propertyName } from './schemaSource';
import type { SchemaDeclarations } from './schemaDeclarations';

export interface OutputOptions {
    includeState?: boolean;
    source?: { entry: string; export: string };
    declarations?: SchemaDeclarations;
}

function schemaMap(name: string, entries: readonly (readonly [string, string])[]): string {
    return `export const ${name} = {\n${entries.map(([key, schema]) => `  ${propertyName(key)}: ${schema},`).join('\n')}\n} as const;\n\n`;
}

function preamble(converter: TypeToZodConverter, options: OutputOptions, expressions: readonly string[]): string {
    let output = '// GENERATED by redemeine extract-schemas — do not edit\n';
    if (options.source) output += `// Source: ${commentText(options.source.entry)} — ${commentText(options.source.export)}\n`;
    output += `// Schema mode: ${converter.policy.mode}; maxDepth: ${converter.policy.maxDepth}\n`;
    output += '// Structural types do not express every runtime validation constraint.\n';
    if (expressions.some(expression => /\bz[.[]/.test(expression))) output += "import { z } from 'zod';\n";
    return output + [...converter.imports].join('\n') + '\n';
}

/**
 * Assembles the final .ts file string with imports, shared schemas,
 * and command/event/state schema exports.
 *
 * Two-phase design: Phase 1 eagerly converts all types so that
 * converter.generatedShared and converter.imports are fully populated.
 * Phase 2 assembles the output string referencing those maps.
 */
export function generateOutput(
    converter: TypeToZodConverter,
    commandPayloads: Map<string, ts.Type>,
    eventPayloads: Map<string, ts.Type>,
    stateType: ts.Type | null,
    options: OutputOptions
): string {
    // --- Phase 1: convert all types eagerly to populate shared schemas & imports ---
    const commandEntries = [...commandPayloads].map(
        ([name, type]) => [name, converter.convert(type, 0, `${options.source?.export ?? 'aggregate'}.commands.${name}`, options.declarations?.commands.get(name))] as const
    );
    const eventEntries = [...eventPayloads].map(
        ([name, type]) => [name, converter.convert(type, 0, `${options.source?.export ?? 'aggregate'}.events.${name}`, options.declarations?.events.get(name))] as const
    );
    const stateZod = options.includeState !== false && stateType
        ? converter.convert(stateType, 0, `${options.source?.export ?? 'aggregate'}.state`, options.declarations?.state)
        : null;

    // --- Phase 2: assemble output now that maps are populated ---
    let output = preamble(converter, options, [...converter.generatedShared.values(),
        ...commandEntries.map(([, schema]) => schema), ...eventEntries.map(([, schema]) => schema), stateZod ?? '']);

    if (converter.generatedShared.size) output += '// Shared payload and state schemas\n';
    for (const [varName, zodCode] of converter.generatedShared) {
        output += `${converter.sharedComments.get(varName) ?? ''}const ${varName} = ${zodCode};\n\n`;
    }
    output += '// Command schemas\n' + schemaMap('commandSchemas', commandEntries);
    output += '// Event schemas\n' + schemaMap('eventSchemas', eventEntries);

    if (stateZod) {
        output += `// Aggregate state\nexport const stateSchema = ${stateZod};\n`;
    }

    return formatSchemaSource(output);
}
